import { mkdir, readFile, rm, stat, writeFile } from 'node:fs/promises'
import { dirname, join, normalize, resolve, sep } from 'node:path'
import {
  DeleteObjectCommand,
  GetObjectCommand,
  HeadObjectCommand,
  PutObjectCommand,
  S3Client,
} from '@aws-sdk/client-s3'
import { env } from '@server/config/env'

/**
 * Storage drivers (decision 2026-10-07): local disk in development, any S3-compatible bucket
 * when `STORAGE_DRIVER=s3`. Both are served through `/api/files/*` (access re-checked, signed,
 * user-bound), never presigned, so switching driver is a config change only.
 */
export interface StorageDriver {
  put(key: string, body: Uint8Array, contentType: string): Promise<void>
  get(key: string): Promise<Uint8Array | null>
  delete(key: string): Promise<void>
  exists(key: string): Promise<boolean>
}

/** Keys are generated by us, but never trust them blindly: no absolute paths, no `..`. */
export function safeKey(key: string) {
  const clean = normalize(key).replace(/^([/\\])+/, '')
  if (clean.startsWith('..') || clean.includes(`..${sep}`) || clean.includes('\0'))
    throw new Error('Invalid storage key')
  return clean
}

export class LocalDiskStorage implements StorageDriver {
  private readonly root: string
  constructor(root: string) {
    this.root = resolve(root)
  }
  private path(key: string) {
    const full = resolve(join(this.root, safeKey(key)))
    if (!full.startsWith(this.root + sep)) throw new Error('Invalid storage key')
    return full
  }
  async put(key: string, body: Uint8Array) {
    const full = this.path(key)
    await mkdir(dirname(full), { recursive: true })
    await writeFile(full, body)
  }
  async get(key: string) {
    try {
      return new Uint8Array(await readFile(this.path(key)))
    } catch {
      return null
    }
  }
  async delete(key: string) {
    await rm(this.path(key), { force: true })
  }
  async exists(key: string) {
    try {
      await stat(this.path(key))
      return true
    } catch {
      return false
    }
  }
}

export class S3Storage implements StorageDriver {
  private readonly client: S3Client
  constructor(private readonly bucket: string) {
    this.client = new S3Client({
      region: env.STORAGE_S3_REGION,
      endpoint: env.STORAGE_S3_ENDPOINT,
      forcePathStyle: Boolean(env.STORAGE_S3_ENDPOINT),
      credentials:
        env.STORAGE_S3_ACCESS_KEY_ID && env.STORAGE_S3_SECRET_ACCESS_KEY
          ? {
              accessKeyId: env.STORAGE_S3_ACCESS_KEY_ID,
              secretAccessKey: env.STORAGE_S3_SECRET_ACCESS_KEY,
            }
          : undefined,
    })
  }
  async put(key: string, body: Uint8Array, contentType: string) {
    await this.client.send(
      new PutObjectCommand({
        Bucket: this.bucket,
        Key: safeKey(key),
        Body: body,
        ContentType: contentType,
      }),
    )
  }
  async get(key: string) {
    try {
      const out = await this.client.send(
        new GetObjectCommand({ Bucket: this.bucket, Key: safeKey(key) }),
      )
      return out.Body ? new Uint8Array(await out.Body.transformToByteArray()) : null
    } catch {
      return null
    }
  }
  async delete(key: string) {
    await this.client.send(new DeleteObjectCommand({ Bucket: this.bucket, Key: safeKey(key) }))
  }
  async exists(key: string) {
    try {
      await this.client.send(new HeadObjectCommand({ Bucket: this.bucket, Key: safeKey(key) }))
      return true
    } catch {
      return false
    }
  }
}

let driver: StorageDriver =
  env.STORAGE_DRIVER === 's3' && env.STORAGE_S3_BUCKET
    ? new S3Storage(env.STORAGE_S3_BUCKET)
    : new LocalDiskStorage(env.STORAGE_LOCAL_DIR)

export function storage(): StorageDriver {
  return driver
}

/** Tests swap in a temp directory. */
export function setStorage(next: StorageDriver) {
  driver = next
}
